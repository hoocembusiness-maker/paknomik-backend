-- Multi-affectation Produits ↔ Kits.
-- Produits : buyer_space_libraryproduct (code unique, secteur, description, is_active).
-- Kits     : buyer_space_suiteensemble (code unique, nom).
-- Ce script crée les tables ajoutées par la migration Django.
-- PostgreSQL. Ne pas l'exécuter si migrate a déjà créé les tables.

CREATE TABLE packaging_kits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_label varchar(40) NOT NULL,
    components_label text NOT NULL DEFAULT '',
    component_count integer NOT NULL DEFAULT 0 CHECK (component_count >= 0),
    remarks text NOT NULL DEFAULT '',
    ensemble_id bigint NOT NULL UNIQUE
        REFERENCES buyer_space_suiteensemble (id) ON DELETE CASCADE
);

CREATE INDEX packaging_kit_status_idx ON packaging_kits (status_label);

CREATE TABLE product_kit_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role varchar(16) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    product_id bigint NOT NULL
        REFERENCES buyer_space_libraryproduct (id) ON DELETE CASCADE,
    kit_id bigint NOT NULL
        REFERENCES buyer_space_suiteensemble (id) ON DELETE RESTRICT,
    CONSTRAINT uniq_product_kit_assignment UNIQUE (product_id, kit_id),
    CONSTRAINT kit_assignment_role_ok CHECK (role IN ('Principal', 'Alternatif'))
);

CREATE UNIQUE INDEX uniq_product_principal_kit
    ON product_kit_assignments (product_id)
    WHERE role = 'Principal';

CREATE INDEX product_kit_role_idx ON product_kit_assignments (role);
CREATE INDEX product_kit_assignments_product_id
    ON product_kit_assignments (product_id);
CREATE INDEX product_kit_assignments_kit_id
    ON product_kit_assignments (kit_id);

CREATE TABLE product_kit_audits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_principal_code varchar(40) NOT NULL DEFAULT '',
    original_alternatives text NOT NULL DEFAULT '',
    decision varchar(40) NOT NULL,
    retained_principal_code varchar(40) NOT NULL DEFAULT '',
    retained_alternatives text NOT NULL DEFAULT '',
    justification text NOT NULL DEFAULT '',
    product_id bigint NOT NULL UNIQUE
        REFERENCES buyer_space_libraryproduct (id) ON DELETE CASCADE
);

CREATE INDEX product_kit_audit_decision ON product_kit_audits (decision);

